/** Rebuild the two-member opening checkpoint exclusively with official commands. */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { initial } from '../../src/simulation/ea-opening-sim.mjs';
import { createGodotBridge } from '../../src/simulation/ea-godot-bridge.mjs';

const sites = JSON.parse(readFileSync(new URL('../../archive/godot/estate_2d/estate-sites.json', import.meta.url))).sites;
const sourceFiles = ['src/simulation/ea-opening-sim.mjs', 'src/simulation/ea-courtyard-visitors.mjs', 'src/simulation/ea-godot-bridge.mjs', 'src/simulation/ea-sr-economy.mjs', 'src/simulation/ea-sr-persons.mjs', 'src/simulation/ea-sr-spatial.mjs', 'src/simulation/ea-sect-domain.mjs', 'src/simulation/ea-state-v6.mjs', 'archive/godot/estate_2d/estate-sites.json'];
const hash = text => createHash('sha256').update(text).digest('hex');
export function buildSectSeed({ enableDomain = true } = {}) {
  const options = { sr: true, mountainOpening: true, seed: 618033 };
  const world = createGodotBridge({ state: initial(options), sites });
  const trace = [];
  function command(name, ...args) {
    const before = world.snapshot();
    const result = world.command({ name, args });
    if (!result.ok) throw Error(`${name}: ${result.error}`);
    trace.push({ kind: 'command', name, args, atTick: before.tick, result: result.result ?? null });
    return result;
  }
  function until(predicate, label, limit = 6000) {
    let steps = 0;
    while (!predicate(world.snapshot()) && steps < limit) { world.advance(.1); steps++; }
    if (!predicate(world.snapshot())) throw Error(`Seed prerequisite did not finish: ${label}`);
    trace.push({ kind: 'advance', label, steps, seconds: steps / 10, atTick: world.snapshot().tick });
  }
  command('masterAction', 'heal');
  command('chooseOpeningInheritance', 'qinglan');
  until(view => view.roster[0].wound === 0, 'opening healing');
  command('advanceStory');
  command('establishHall');
  until(view => view.openingHallPhase === 'complete', 'main hall construction');
  until(view => view.people.find(p => p.id === 'person:lu-zhiwei')?.visit?.phase === 'present', 'visitor reaches courtyard');
  const visitor = world.snapshot().people.find(p => p.id === 'person:lu-zhiwei');
  command('moveScenicMaster', visitor.x + 1, visitor.y);
  until(view => view.openingStory.visitor.canTalk, 'master approaches visitor');
  command('advanceStory', 'gift');
  command('advanceStory', 'invite');
  const farm = sites.find(site => site.type === 'farm');
  command('build', 'farm', farm.x, farm.y);
  until(view => view.buildings.some(b => b.type === 'farm' && b.stage === 'complete'), 'herb terrace construction');
  command('masterAction', 'rest');
  if (enableDomain) command('enableSectDomain');
  const state = JSON.parse(world.save());
  if (state.homeMemberIds.length !== 1 || state.homeMemberIds[0] !== 'person:lu-zhiwei') throw Error('Expected master and Lu Zhiwei as the two sect residents');
  const provenance = {
    kind: 'normal-public-command-checkpoint', id: enableDomain ? 'yunxiu-two-members-east-domain-v1' : 'yunxiu-two-members-herb-terrace-v1',
    source: 'SIM.initial + createGodotBridge public command sequence',
    sourceRevision: '62feae4e38a1e28c50e076031064d9330794c55d', initialOptions: options,
    sourceFiles: Object.fromEntries(sourceFiles.map(path => [path, hash(readFileSync(new URL(`../../${path}`, import.meta.url)))])),
    trace, stateSha256: hash(JSON.stringify(state)),
    residentIds: ['person:master', ...state.homeMemberIds],
    description: '已疗伤择卷、赠药并取得陆知微入院同意；主殿与药圃由正常命令营造完成，药圃尚未送苗。' + (enableDomain ? '已采用东侧山域布局，东台门人居由玩家选择营造。' : '')
  };
  return { provenance, state };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const seed = buildSectSeed();
  writeFileSync(new URL('./sect-seed.mjs', import.meta.url), `// Generated by sect-seed-build.mjs through official public commands.\nexport default ${JSON.stringify(seed)};\n`);
  console.log(JSON.stringify({ tick: seed.state.worldTick, members: seed.provenance.residentIds, resources: seed.state.stockpilesById['stockpile:yunxiu'].resources, sha256: seed.provenance.stateSha256 }));
}
